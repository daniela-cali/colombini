<h5><i class="fas fa-edit mr-1"></i> Modifica articolo</h5>
<p>Aggiorna i dati dell'articolo. La <strong>giacenza corrente</strong> non è modificabile da qui: viene calcolata dai movimenti di magazzino.</p>
<p>Per correggere una giacenza errata usa un movimento di tipo <em>Rettifica (+)</em> o <em>Rettifica (−)</em>.</p>
