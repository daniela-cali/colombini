<h5><i class="fas fa-box mr-1"></i> Scheda articolo</h5>
<p>Visualizza i dati dell'articolo e lo storico completo dei movimenti (carichi, scarichi, rettifiche, giacenza iniziale) dal più recente.</p>
<h5><i class="fas fa-trash mr-1"></i> Eliminazione</h5>
<p>Non è possibile eliminare un articolo che ha movimenti registrati, per preservare la storicità dei dati.</p>
