<h5><i class="fas fa-map-marker-alt mr-1"></i> Posizioni scaffale</h5>
<p>Definisci le zone fisiche del magazzino (es. SCAFFALE BLU, PANNELLO MURO). Ogni articolo può essere assegnato a una posizione per facilitarne il ritrovamento.</p>
<h5><i class="fas fa-eye-slash mr-1"></i> Disattivare una posizione</h5>
<p>Deselezionando <strong>Posizione attiva</strong> la posizione scompare dai menu di selezione, ma gli articoli già assegnati la mantengono fino alla prossima modifica.</p>
<h5><i class="fas fa-trash mr-1"></i> Eliminazione</h5>
<p>Non è possibile eliminare una posizione se ha articoli assegnati. Riassegna prima gli articoli a un'altra posizione.</p>
