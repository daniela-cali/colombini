<h5><i class="fas fa-tags mr-1"></i> Categorie magazzino</h5>
<p>Definisci le categorie usate per classificare gli articoli. Compaiono nei filtri dell'elenco articoli e nei menu di selezione.</p>
<h5><i class="fas fa-sort-numeric-down mr-1"></i> Ordine</h5>
<p>Determina la sequenza di apparizione nei filtri. Numeri più bassi compaiono prima.</p>
<h5><i class="fas fa-eye-slash mr-1"></i> Disattivare una categoria</h5>
<p>Deselezionando <strong>Categoria attiva</strong> la categoria scompare dai filtri e dai menu, ma gli articoli già assegnati la mantengono.</p>
