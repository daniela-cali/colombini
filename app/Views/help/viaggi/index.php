<h5><i class="fas fa-route mr-1"></i> Elenco viaggi per data</h5>
<p>Mostra tutti i viaggi pianificati per la giornata selezionata, raggruppati in due sezioni: <strong>Bozze</strong> (ancora modificabili) e <strong>Approvati</strong> (operativi). Usa il campo data in alto per navigare tra i giorni.</p>

<h5><i class="fas fa-car mr-1"></i> Veicolo e tappe in bozza</h5>
<p>Per ogni viaggio in bozza vengono mostrati il numero di tappe e il veicolo già assegnato (se presente). L'icona <i class="fas fa-exclamation-triangle text-warning"></i> segnala un viaggio ancora senza mezzo — non sarà possibile approvarlo finché non se ne assegna uno.</p>

<h5><i class="fas fa-print mr-1"></i> Stampa giornata</h5>
<p>Il pulsante <strong>Stampa giornata</strong> appare solo quando esistono viaggi approvati. Genera un PDF riepilogativo con tutte le tappe di tutti i tecnici per il giorno selezionato.</p>

<h5><i class="fas fa-eye mr-1"></i> Dettaglio viaggio</h5>
<p>Clicca sull'icona <strong>occhio</strong> per aprire il dettaglio del viaggio: elenco tappe, veicolo assegnato, distanza totale e stato di ogni intervento.</p>

<p><span class="badge-tip"><i class="fas fa-lightbulb mr-1"></i> I viaggi vengono creati dall'interfaccia di pianificazione. Da qui puoi approvarli, stamparli o eliminarli.</span></p>
