<h5><i class="fas fa-map-marked-alt mr-1"></i> Dettaglio viaggio</h5>
<p>Mostra il tecnico assegnato, il veicolo (con targa), la data e le tappe nell'ordine pianificato. Per ogni tappa sono indicati il cliente, il tipo di intervento, la priorità e l'orario di arrivo stimato.</p>

<h5><i class="fas fa-car mr-1"></i> Veicolo assegnato</h5>
<p>La scheda <strong>Veicolo assegnato</strong> permette di scegliere o cambiare il mezzo sia per le bozze che per i viaggi approvati. I veicoli evidenziati in rosso sono riservati a un altro tecnico; quelli in grigio sono già impegnati per la stessa data. Non è possibile approvare un viaggio senza un veicolo.</p>

<h5><i class="fas fa-check mr-1"></i> Approva</h5>
<p>Un viaggio in stato <strong>Bozza</strong> deve essere approvato prima di diventare operativo. All'approvazione gli interventi vengono assegnati al tecnico e passano in stato <strong>Pianificato</strong>.</p>

<h5><i class="fas fa-lock-open mr-1"></i> Riapri</h5>
<p>Se un viaggio è già <strong>Approvato</strong> e devi modificarne le tappe, clicca <strong>Riapri</strong> per riportarlo in stato Bozza. Le tappe rimangono invariate e il veicolo assegnato viene conservato. Poi torna nella pianificazione per spostare o aggiungere interventi e approva di nuovo.</p>

<h5><i class="fas fa-print mr-1"></i> Stampa foglio di viaggio</h5>
<p>Il pulsante <strong>Stampa</strong> genera un PDF con tutte le tappe del tecnico per la giornata, pronto per essere stampato o inviato. Per uso interno, senza spazio firma.</p>

<h5><i class="fas fa-times mr-1"></i> Elimina</h5>
<p>Eliminando un viaggio (bozza o approvato) tutti gli interventi tornano in stato <strong>Da pianificare</strong> e il tecnico viene rimosso dall'assegnazione.</p>

<p><span class="badge-tip"><i class="fas fa-lock mr-1"></i> L'icona lucchetto accanto a una priorità indica un orario fissato che il pianificatore non può spostare.</span></p>
