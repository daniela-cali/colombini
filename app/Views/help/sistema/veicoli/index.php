<h5><i class="fas fa-truck mr-1"></i> Veicoli aziendali</h5>
<p>Elenco dei mezzi aziendali utilizzati per gli interventi sul campo. Ogni veicolo è identificato da un nome descrittivo e dalla targa, che deve essere univoca.</p>
<h5><i class="fas fa-toggle-on mr-1"></i> Stato</h5>
<p>I veicoli con stato <strong>Disattivo</strong> non saranno disponibili per la selezione nei nuovi interventi, ma i dati storici vengono conservati.</p>
<h5><i class="fas fa-trash mr-1"></i> Eliminazione</h5>
<p>È possibile eliminare un veicolo solo se non è ancora associato ad alcun intervento. In caso contrario <strong>disattivalo</strong> invece di eliminarlo.</p>
